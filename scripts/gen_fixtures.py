"""
Generate SYNTHETIC test fixtures for load-testing and UI development.

Why this exists
---------------
Mockaroo, Faker (``fakerjs.dev`` / Python ``Faker``) and friends are useful —
and in a warning system they are dangerous in a specific way: a generated row
that looks like a real resident can end up in a real send. HeatShield's
hard rule (`AGENTS.md` §6.1) is *never fabricate data*, so this generator is
built to make misuse difficult and obvious:

1. **It writes outside the data directories.** The default output is
   ``/tmp``-style scratch, never ``data/subscribers.csv``. ``--out`` will refuse
   to overwrite the live registry unless you pass ``--i-know-what-im-doing``.
2. **Every row is labelled.** ``synthetic: true``, a ``note`` column, and the
   generator's seed travel with the data.
3. **The phone numbers cannot dial out.** They are drawn from the reserved
   ``+91 0000 00xxxx`` block the existing demo registry already uses, so a
   misrouted load test fails loudly at the provider instead of texting a
   stranger.
4. **Live dispatch refuses them.** ``core.alerts.dispatch`` is dry-run by
   default behind two independent locks, and the registry loader marks rows
   from this generator so an operator can see them.

Deterministic: the same ``--seed`` always produces the same file, so a load
test is reproducible and a CI budget check does not flap.

Run
---
    python -m scripts.gen_fixtures --subscribers 5000 --out /tmp/subs.csv
    python -m scripts.gen_fixtures --wards 141 --hours 144 --out /tmp/load.csv
"""
from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[1]
LIVE_REGISTRY = BASE_DIR / "data" / "subscribers.csv"

#: Reserved, unroutable Indian number block — the same convention the committed
#: demo registry uses. A generated number can never reach a real handset.
SYNTHETIC_PREFIX = "+9100000"
SYNTHETIC_NOTE = "SYNTHETIC TEST FIXTURE — generated by scripts.gen_fixtures, never send"

ROLES = ("resident", "volunteer", "worker", "official", "clinic")
BANDS = ("Caution", "Danger", "Critical", "Extreme")


# --------------------------------------------------------------------------- #
# Generators
# --------------------------------------------------------------------------- #

def subscribers(count: int, *, seed: int, ward_ids: range) -> list[dict]:
    rng = random.Random(seed)
    rows = []
    for i in range(count):
        suffix = f"{i:05d}"[-5:]
        rows.append({
            "phone": f"{SYNTHETIC_PREFIX}{suffix}",
            "ward_id": rng.choice(list(ward_ids)),
            "name": f"LOADTEST {i:05d}",
            "role": rng.choice(ROLES),
            "synthetic": "true",
            "note": SYNTHETIC_NOTE,
        })
    return rows


def ward_hours(wards: int, hours: int, *, seed: int) -> list[dict]:
    """A ward-hour frame shaped like ``core.weather.get_forecast()`` output.

    Numbers are plausible and internally consistent (RH falls as T rises, solar
    is zero at night) so a chart built from them behaves like a real one. They
    are still synthetic, and the header says so.
    """
    rng = random.Random(seed)
    start = datetime(2026, 5, 18, 0, 0, tzinfo=timezone(timedelta(hours=5, minutes=30)))
    rows = []
    for ward in range(1, wards + 1):
        for hour in range(hours):
            stamp = start + timedelta(hours=hour)
            day_fraction = max(0.0, 1 - abs(stamp.hour - 13) / 7.0)
            solar = round(950 * day_fraction, 1)
            temp = round(30 + 8 * day_fraction + rng.uniform(-0.6, 0.6), 2)
            rh = round(max(25, 85 - 35 * day_fraction + rng.uniform(-3, 3)), 1)
            rows.append({
                "ward_id": ward,
                "ward_name": f"Ward {ward}",
                "lat": round(22.57 + rng.uniform(-0.09, 0.09), 6),
                "lon": round(88.36 + rng.uniform(-0.09, 0.09), 6),
                "elevation_m": round(rng.uniform(2, 12), 1),
                "timestamp_local": stamp.isoformat(),
                "temp_c": temp,
                "rh_pct": rh,
                "dewpoint_c": round(temp - (100 - rh) / 5, 2),
                "wind_kmh": round(rng.uniform(1, 15), 1),
                "solar_wm2": solar,
                "synthetic": "true",
            })
    return rows


# --------------------------------------------------------------------------- #
# Safety
# --------------------------------------------------------------------------- #

def _check_destination(path: Path, force: bool) -> None:
    if path.resolve() == LIVE_REGISTRY.resolve() and not force:
        raise SystemExit(
            f"refusing to overwrite the live subscriber registry ({LIVE_REGISTRY}).\n"
            "Load-test fixtures are not residents. Pass --i-know-what-im-doing\n"
            "only if you are deliberately reseeding the demo registry."
        )
    if path.exists() and not force and path.stat().st_size > 0:
        raise SystemExit(
            f"{path} already exists — pass --force to overwrite it."
        )


def write_csv(rows: list[dict], path: Path) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return 0
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return len(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--subscribers", type=int, default=0,
                        help="how many synthetic subscriber rows to generate")
    parser.add_argument("--wards", type=int, default=0,
                        help="ward-hour fixture: how many wards")
    parser.add_argument("--hours", type=int, default=0,
                        help="ward-hour fixture: hours per ward")
    parser.add_argument("--out", type=Path, required=True, help="output CSV path")
    parser.add_argument("--seed", type=int, default=20260518,
                        help="RNG seed — the same seed always yields the same file")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--i-know-what-im-doing", action="store_true",
                        help="allow writing over data/subscribers.csv")
    args = parser.parse_args(argv)

    if not (args.subscribers or (args.wards and args.hours)):
        parser.error("generate something: --subscribers N, or --wards N --hours N")

    _check_destination(args.out, args.force or args.i_know_what_im_doing)

    if args.subscribers:
        rows = subscribers(args.subscribers, seed=args.seed, ward_ids=range(1, 142))
    else:
        rows = ward_hours(args.wards, args.hours, seed=args.seed)

    written = write_csv(rows, args.out)
    summary = {
        "rows": written,
        "out": str(args.out),
        "seed": args.seed,
        "synthetic": True,
        "note": SYNTHETIC_NOTE,
        "generated_at_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
    }
    print(json.dumps(summary, indent=2))
    print(f"\nwrote {written:,} synthetic rows -> {args.out}")
    print(f"every row carries synthetic=true — {SYNTHETIC_NOTE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
