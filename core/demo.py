def forecast_payload(scenario_id: str, zone_id: str | None = None) -> dict[str, Any]:
    """Meteorological forecast view: daily summaries with lead times + full hourly."""
    frame = scenario_frame(scenario_id)
    if zone_id is not None:
        frame = frame[frame["zone_id"] == zone_id].copy()
        if frame.empty:
            raise KeyError(zone_id)
    climatology = load_climatology()

    frame["date"] = frame["timestamp_local"].dt.date
    daily = (
        frame.groupby(["zone_id", "zone_name", "lat", "lon", "date"], as_index=False)
        .agg(
            tmax_c=("temp_c", "max"),
            tmin_c=("temp_c", "min"),
            rh_min_pct=("rh_pct", "min"),
            rh_mean_pct=("rh_pct", "mean"),
            wind_mean_kmh=("wind_kmh", "mean"),
            solar_max_wm2=("solar_wm2", "max"),
            precip_mm=("precip_mm", "sum"),
            pm25_mean_ugm3=("pm25_ugm3", "mean"),
            pm25_peak_ugm3=("pm25_ugm3", "max"),
            aqi_peak=("aqi_india", "max"),
            heat_aqi_load_peak=("heat_aqi_load", "max"),
        )
        .sort_values(["zone_id", "date"])
    )
    daily["aqi_band"] = [aqi_band(v) for v in daily["aqi_peak"]]
    daily["heat_aqi_load_band"] = [aqi_band(v) for v in daily["heat_aqi_load_peak"]]

    normals, departures = [], []
    for record in daily.to_dict("records"):
        normal, _gran = climatology_normal(climatology, record["zone_id"], record["date"])
        normals.append(round(normal, 1) if normal is not None else None)
        departures.append(round(record["tmax_c"] - normal, 1) if normal is not None else None)
    daily["normal_tmax_c"] = normals
    daily["departure_c"] = departures

    issue_date = DEMO_ISSUED_AT_LOCAL.normalize().date()
    daily["lead_days"] = [(pd.Timestamp(d).date() - issue_date).days for d in daily["date"]]
    daily["target_day_label"] = [f"Day +{lead}" for lead in daily["lead_days"]]
    daily["date"] = daily["date"].astype(str)

    daily_cols = [
        "zone_id", "zone_name", "lat", "lon", "date", "target_day_label", "lead_days",
        "tmax_c", "tmin_c", "rh_min_pct", "rh_mean_pct", "wind_mean_kmh", "solar_max_wm2",
        "precip_mm", "pm25_mean_ugm3", "pm25_peak_ugm3", "aqi_peak", "aqi_band",
        "heat_aqi_load_peak", "heat_aqi_load_band", "normal_tmax_c", "departure_c",
    ]
    daily_records = _clean_records(daily[daily_cols].round(
        {"tmax_c": 1, "tmin_c": 1, "rh_min_pct": 1, "rh_mean_pct": 1, "wind_mean_kmh": 1,
         "solar_max_wm2": 0, "precip_mm": 1, "pm25_mean_ugm3": 1, "pm25_peak_ugm3": 1}))

    hourly_cols = ["zone_id", "timestamp_local", "lead_days", "temp_c", "rh_pct", "wind_kmh",
                   "solar_wm2", "precip_mm", "pm25_ugm3", "aqi_india", "heat_aqi_load"]
    hourly = frame.copy()
    hourly["lead_days"] = [(ts.normalize() - DEMO_ISSUED_AT_LOCAL.normalize()).days
                           for ts in hourly["timestamp_local"]]
    # Hourly detail covers the issue day ("current conditions" chart); the
    # 5-day outlook is the daily table with explicit lead times. Keeping the
    # full 6×24 grid in every static payload would triple its size for curves
    # no screen renders.
    hourly = hourly[hourly["lead_days"] == 0]
    hourly["timestamp_local"] = hourly["timestamp_local"].dt.strftime("%Y-%m-%dT%H:%M")
    hourly_records = _clean_records(hourly[hourly_cols].round(
        {"temp_c": 1, "rh_pct": 0, "wind_kmh": 1, "solar_wm2": 0, "precip_mm": 1,
         "pm25_ugm3": 0, "aqi_india": 0, "heat_aqi_load": 0}))

    return _envelope(
        scenario_id,
        zone_id=zone_id,
        rows_daily=len(daily_records),
        rows_hourly=len(hourly_records),
        hourly_scope="issue day (Day +0) only — the daily table carries the full 5-day outlook",
        granularity_note=(
            "Zone-level model values (~10 km grid) — not ward-level observations."
        ),
        climatology_note=(
            "normal_tmax_c comes from the REAL fixed 1991–2020 normals "
            "(data/climatology_normals.json); the weather around it is synthetic."
        ),
        daily=daily_records,
        hourly=hourly_records,
    )


def thermal_payload(scenario_id: str, zone_id: str | None = None) -> dict[str, Any]:
    """HTSI view: daily thermal metrics + quality flags + issue-day hourly detail."""
    from core.htsi import HTSI_METADATA, QUALITY_DEFINITIONS, daily_htsi

    frame = scenario_frame(scenario_id)
    climatology = load_climatology()

    # Anomaly term of the HTSI = departure of the DAY's Tmax from the fixed
    # 1991–2020 normal, applied uniformly to every hour of that day (an
    # hour-by-hour departure would let overnight cooling erase the anomaly).
    frame["date"] = frame["timestamp_local"].dt.date
    daily_tmax = frame.groupby(["zone_id", "date"], sort=False)["temp_c"].max()
    departures_by_key: dict[tuple[str, Any], float] = {}
    for (zone_key, date_key), tmax_value in daily_tmax.items():
        normal, _gran = climatology_normal(climatology, zone_key, date_key)
        if normal is not None:
            departures_by_key[(zone_key, date_key)] = float(tmax_value) - float(normal)
    frame["departure_c"] = pd.Series(
        [departures_by_key.get((z, d), np.nan) for z, d in zip(frame["zone_id"], frame["date"])],
        index=frame.index, dtype="float64",
    )

    thermal_hourly = compute_htsi_frame(frame, departure_c=frame["departure_c"])
    # Recompute the score with the anomaly term for hourly rows too.
    scores = [htsi_score(w, d) for w, d in zip(thermal_hourly["wbgt_est_c"], thermal_hourly["departure_c"])]
    thermal_hourly["htsi_score"] = scores
    thermal_hourly["htsi_band"] = [htsi_band(s)["band"] for s in scores]

    daily = daily_htsi(thermal_hourly)
    # attach normals + rescore with the Tmax-vs-normal anomaly at the daily peak
    normals, grans, deps, rescored, anomaly_used = [], [], [], [], []
    for record in daily.to_dict("records"):
        normal, gran = climatology_normal(climatology, record["zone_id"], record["date"])
        dep = round(record["tmax_c"] - normal, 1) if normal is not None and record.get("tmax_c") is not None else None
        score = htsi_score(record.get("wbgt_est_peak_c"), dep)
        base = htsi_score(record.get("wbgt_est_peak_c"), None)
        normals.append(round(normal, 2) if normal is not None else None)
        grans.append(gran)
        deps.append(dep)
        rescored.append(score)
        anomaly_used.append(bool(score is not None and base is not None
                                 and abs(score - base) > 1e-9))
    daily["normal_tmax_c"] = normals
    daily["normal_granularity"] = grans
    daily["departure_c"] = deps
    daily["htsi_score"] = rescored
    daily["htsi_anomaly_used"] = anomaly_used
    daily["htsi_band"] = [htsi_band(s)["band"] for s in daily["htsi_score"]]
    daily["date"] = daily["date"].astype(str)
    issue_date = DEMO_ISSUED_AT_LOCAL.normalize().date()
    daily["lead_days"] = [(pd.Timestamp(d).date() - issue_date).days for d in daily["date"]]

    if zone_id is not None:
        daily = daily[daily["zone_id"] == zone_id].copy()
        thermal_hourly = thermal_hourly[thermal_hourly["zone_id"] == zone_id].copy()
        if daily.empty:
            raise KeyError(zone_id)

    daily_cols = [
        "zone_id", "date", "lead_days", "tmax_c", "normal_tmax_c", "normal_granularity",
        "departure_c", "hi_peak_c", "wbgt_est_peak_c", "wbgt_peak_quality", "wbgt_peak_inputs",
        "htsi_score", "htsi_band", "htsi_anomaly_used",
    ]
    hourly_view = thermal_hourly.copy()
    # Same scoping rule as the forecast payload: hourly detail for the issue
    # day only; every outlook day is covered by the daily thermal table.
    issue_day = DEMO_ISSUED_AT_LOCAL.normalize()
    hourly_view = hourly_view[hourly_view["timestamp_local"].dt.normalize() == issue_day]
    hourly_view["timestamp_local"] = hourly_view["timestamp_local"].dt.strftime("%Y-%m-%dT%H:%M")
    hourly_cols = ["zone_id", "timestamp_local", "temp_c", "rh_pct", "wind_kmh", "solar_wm2",
                   "wet_bulb_c", "globe_c", "heat_index_c", "wbgt_est_c", "wbgt_quality",
                   "htsi_score", "htsi_band"]
    return _envelope(
        scenario_id,
        zone_id=zone_id,
        method=HTSI_METADATA,
        quality_definitions=QUALITY_DEFINITIONS,
        wbgt_statement=(
            "wbgt_est_c is an ESTIMATED WBGT computed from scenario weather inputs with the "
            "ISO 7243 outdoor formula. It is not a measured globe-thermometer WBGT and must "
            "never be labelled as one."
        ),
        hourly_scope="issue day (Day +0) only — the daily table carries the full 5-day outlook",
        rows_daily=len(daily),
        rows_hourly=len(hourly_view),
        daily=_clean_records(daily[daily_cols]),
        hourly=_clean_records(hourly_view[hourly_cols].round(
            {"temp_c": 1, "rh_pct": 0, "wind_kmh": 1, "solar_wm2": 0, "wet_bulb_c": 1,
             "globe_c": 1, "heat_index_c": 1, "wbgt_est_c": 1})),
    )


def warnings_payload(scenario_id: str, zone_id: str | None = None) -> dict[str, Any]:
    """Operational 3–5 day advance-warning rows for a demo scenario."""
    frame = scenario_frame(scenario_id)
    if zone_id is not None:
        frame = frame[frame["zone_id"] == zone_id].copy()
        if frame.empty:
            raise KeyError(zone_id)
    climatology = load_climatology()
    rows = build_warning_rows(
        frame,
        issued_at=DEMO_ISSUED_AT_LOCAL,
        quality_state="demo-synthetic",
        data_source=DEMO_DATA_SOURCE_TEMPLATE.format(scenario=scenario_id),
        is_demo=True,
        scenario_id=scenario_id,
        climatology=climatology,
        fallback_reason=None,
    )
    lead_counts: dict[str, int] = {}
    level_counts: dict[str, int] = {}
    for row in rows:
        lead_counts[str(row["lead_days"])] = lead_counts.get(str(row["lead_days"]), 0) + 1
        level_counts[row["alert_level"]] = level_counts.get(row["alert_level"], 0) + 1
    payload = _envelope(
        scenario_id,
        zone_id=zone_id,
        rows=len(rows),
        lead_day_counts=lead_counts,
        alert_level_counts=level_counts,
        data=rows,
    )
    payload.update(warnings_meta(issued_at=DEMO_ISSUED_AT_LOCAL, climatology=climatology,
                                 is_demo=True, scenario_id=scenario_id))
    payload["rows"] = len(rows)
    return payload


def notifications_payload(scenario_id: str) -> dict[str, Any]:
    """Dry-run notification previews generated from this scenario's warnings."""
    from core.notify import plan_notifications

    rows = warnings_payload(scenario_id)["data"]
    plan = plan_notifications(rows, is_demo=True, scenario_id=scenario_id)
