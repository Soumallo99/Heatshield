def _diurnal_shape(hour: float) -> float:
    """1.0 at 15:00 local peak, −1.0 at 03:00 trough."""
    return math.cos((hour - 15.0) * 2.0 * math.pi / 24.0)


def _solar_shape(hour: float) -> float:
    """Clear-ish sky bell from 06:00 to 18:00, peaking at noon."""
    if hour <= 6.0 or hour >= 18.0:
        return 0.0
    return math.sin(math.pi * (hour - 6.0) / 12.0)


def _hour_values(scenario: dict[str, Any], day_index: int, hour: float, zone_offset: float) -> dict[str, float]:
    tmax = scenario["tmax"][day_index] + zone_offset
    tmin = tmax - scenario["tmin_offset"][day_index]
    shape = _diurnal_shape(hour)
    temp = (tmax + tmin) / 2.0 + (tmax - tmin) / 2.0 * shape

    rh_peak = max(8.0, scenario["rh_at_peak"][day_index] - 1.6 * zone_offset)
    rh_night = min(97.0, scenario["rh_overnight"][day_index] - 1.2 * zone_offset)
    rh_mid = (rh_night + rh_peak) / 2.0
    rh = rh_mid - (rh_mid - rh_peak) * ((shape + 1.0) / 2.0)

    solar = scenario["solar_peak"][day_index] * _solar_shape(hour)
    wind = max(1.0, scenario["wind_base_kmh"][day_index]
               + 2.6 * math.sin((hour - 13.0) * 2.0 * math.pi / 24.0)
               - 0.35 * abs(zone_offset))

    pm_base = scenario["pm25_base"][day_index] + 4.0 * abs(zone_offset)
    # Nighttime inversion peak around 03:00 + a small evening cooking bump.
    pm = pm_base * (1.0 + 0.42 * math.cos((hour - 3.0) * 2.0 * math.pi / 24.0)
                    + 0.10 * math.exp(-((hour - 20.0) / 1.6) ** 2))

    precip = 0.0
    day_precip = scenario["precip_day_mm"][day_index]
    if day_precip > 0 and 15.0 <= hour <= 20.0:
        precip = day_precip / 5.0 * max(0.0, math.sin(math.pi * (hour - 15.0) / 5.0))

    return {
        "temp_c": round(min(temp, 54.0), 2),
        "rh_pct": round(min(max(rh, 5.0), 99.0), 1),
        "wind_kmh": round(wind, 2),
        "solar_wm2": round(max(0.0, solar), 1),
        "pm25_ugm3": round(max(6.0, pm), 1),
        "precip_mm": round(precip, 2),
    }


def scenario_frame(scenario_id: str, zones: pd.DataFrame | None = None) -> pd.DataFrame:
    """Full deterministic hourly frame for a scenario: 8 zones × 6 days × 24 h.

    Column-compatible with ``core.coupled`` frames (so ncr_daily /
    detect_heatwaves / HTSI consume it unchanged) plus explicit demo labels.
    """
    if scenario_id not in SCENARIOS:
        raise KeyError(f"unknown demo scenario '{scenario_id}' — see /demo/scenarios")
    scenario = SCENARIOS[scenario_id]
    zone_table = ncr_zones() if zones is None else zones

    # The scenario clock starts at midnight of the issue day; the 06:00
    # issuance time still drives every lead-time calculation (lead_hours to
    # Day +0's 15:00 peak is +9 h). Hours before 06:00 on Day +0 stand in for
    # the analysis window a real 06:00 bulletin would summarise.
    hours = pd.date_range(start=DEMO_ISSUED_AT_LOCAL.normalize(), periods=DEMO_DAYS * 24, freq="h")
    rows: list[dict[str, Any]] = []
    for zone in zone_table.to_dict("records"):
        offset = ZONE_HEAT_OFFSET.get(str(zone["zone_id"]), 0.0)
        for ts in hours:
            day_index = (ts.normalize() - DEMO_ISSUED_AT_LOCAL.normalize()).days
            values = _hour_values(scenario, day_index, ts.hour + ts.minute / 60.0, offset)
            rows.append({
                "zone_id": zone["zone_id"],
                "zone_name": zone["zone_name"],
                "lat": zone["lat"],
                "lon": zone["lon"],
                "timestamp_local": ts,
                **values,
                "pm10_ugm3": round(values["pm25_ugm3"] * 1.55, 1),
                "surface_pressure_hpa": 1004.0 - 0.6 * day_index,
            })

    frame = _apply_coupling(pd.DataFrame(rows))
    frame["data_source"] = DEMO_DATA_SOURCE_TEMPLATE.format(scenario=scenario_id)
    frame["is_synthetic"] = True
    frame["is_demo"] = True
    frame["scenario_id"] = scenario_id
    frame["issued_at"] = DEMO_ISSUED_AT_LOCAL.strftime("%Y-%m-%dT%H:%M")
    frame["fetched_at"] = "2026-05-18T00:30:00+00:00"   # fixed scenario issuance, UTC
    return frame.sort_values(["zone_id", "timestamp_local"]).reset_index(drop=True)


