/* Generate the crawler/SEO files from one source of truth: the site URL.
 *
 * Why generated rather than committed: `robots.txt`, `sitemap.xml` and
 * `llms.txt` all have to contain an absolute URL, and the deployment URL is not
 * known when the repository is written — it is `https://<owner>.github.io/<repo>/`
 * on GitHub Pages and something else entirely behind a custom domain. A
 * hard-coded URL in three files is three places to forget.
 *
 *   VITE_SITE_URL=https://heatshield.example/ npm run build
 *
 * The same value feeds the canonical link, the Open Graph tags and the
 * structured data in index.html (see the `siteMeta` plugin in vite.config.js),
 * so a custom domain is one variable, not a scavenger hunt.
 *
 * Files land in `public/`, which Vite copies verbatim into `dist/`. They are
 * gitignored like the other build output (see .gitignore).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const PUBLIC = resolve(HERE, '..', 'public')

// The default is this repository's GitHub Pages project URL. Override it with
// VITE_SITE_URL for a custom domain, or when deploying anywhere else.
export const DEFAULT_SITE_URL = 'https://soumallo99.github.io/Heatshield/'

export function siteUrl() {
  const raw = process.env.VITE_SITE_URL || DEFAULT_SITE_URL
  // Normalise: absolute, https, single trailing slash.
  const url = new URL(raw)
  url.hash = ''
  return url.href.endsWith('/') ? url.href : `${url.href}/`
}

/* The pages, with their titles and descriptions, come from
 * `src/site-pages.json` — the same file the app reads to set document.title on
 * navigation. One list, so a page cannot be described one way to a crawler and
 * another way to a reader. */
export const PAGES = Object.entries(
  JSON.parse(readFileSync(resolve(HERE, '..', 'src', 'site-pages.json'), 'utf8')),
).map(([id, page]) => ({ id, ...page }))

/** Pages a crawler should be told about: everything but the 404. */
export const INDEXABLE = PAGES.filter((page) => !page.noindex)

function robots(url) {
  return `# HeatShield — ${url}
#
# Everything a crawler can reach is public, read-only and needs no credentials.
# The administrative API routes (/api/subscribers*, /api/alerts/dispatch,
# /api/notifications/dispatch) are gated and answer 401/503 to anyone without a
# token; they are disallowed here as well so that a crawler does not even
# discover the shape of them.

User-agent: *
Allow: /
Disallow: /api/subscribers
Disallow: /api/subscribers/
Disallow: /api/alerts/dispatch
Disallow: /api/notifications/dispatch

# Generated snapshot data is fetched by the app, not read by people.
Disallow: /static-api/

Sitemap: ${url}sitemap.xml
`
}

function sitemap(url, today) {
  // `notfound` is a real page with its own title, but a 404 in a sitemap is a
  // mistake every crawler reports, so it is excluded by its `noindex` flag.
  const entries = INDEXABLE.map(
    (page) => `  <url>
    <loc>${url}${page.path ? `#/${page.path}` : ''}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${page.id === 'dashboard' || page.id === 'phone' ? 'daily' : 'monthly'}</changefreq>
    <priority>${page.id === 'landing' ? '1.0' : page.id === 'phone' || page.id === 'dashboard' ? '0.9' : '0.5'}</priority>
  </url>`,
  )
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by frontend/web/scripts/gen-site-meta.mjs — edit PAGES there. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.join('\n')}
</urlset>
`
}

/**
 * llms.txt — the convention (https://llmstxt.org) for telling language models
 * what a site is. Worth writing down here rather than letting a model guess:
 * this project's whole claim is that it does not invent data, and an unchecked
 * summary of a heat-warning tool is exactly the kind of thing that ends up
 * quoted as if it were an official advisory.
 */
function llms(url) {
  const lines = INDEXABLE.map(
    (page) => `- [${page.title}](${url}${page.path ? `#/${page.path}` : ''}): ${page.description}`,
  )
  return `# HeatShield

> Ward-level extreme heat early warning and human thermal stress (WBGT) mapping
> for Kolkata (141 KMC wards) and Delhi NCR (8 zones). Open source, keyless by
> construction: no API keys are required to run or deploy it.

HeatShield is a decision-support prototype, not an official warning service. It
does not issue government advisories and its output is not a substitute for one.
Numbers come from named public sources; where a source is absent the interface
says so rather than filling the gap.

## Pages
${lines.join('\n')}

## Data sources
- Open-Meteo (keyless) — weather forecast, air quality, solar radiation
- Census of India 2011 + KMC ward boundaries — population and geography
- Esri World Imagery, OpenStreetMap, OpenTopoMap — basemap tiles
- Re:Earth / Mapterhorn — terrain (CC BY 4.0)

## Usage notes for assistants
- Treat figures as forecast-derived estimates, and always carry the timestamp the
  interface shows. The operations console states the forecast run it is showing.
- The Heat Risk Demo is labelled synthetic data; never present it as observed.
- Do not describe HeatShield as an official or government service.

## Contact
Repository: https://github.com/Soumallo99/Heatshield
`
}

export function generate({ url = siteUrl(), today = new Date().toISOString().slice(0, 10) } = {}) {
  mkdirSync(PUBLIC, { recursive: true })
  const written = {
    'robots.txt': robots(url),
    'sitemap.xml': sitemap(url, today),
    'llms.txt': llms(url),
  }
  for (const [name, contents] of Object.entries(written)) {
    writeFileSync(resolve(PUBLIC, name), contents, 'utf8')
  }
  return { url, files: Object.keys(written) }
}

// Importable (the build plugin uses that) and runnable directly (npm run gen:meta).
if (process.argv[1] && process.argv[1].endsWith('gen-site-meta.mjs')) {
  const { url, files } = generate()
  console.log(`site meta -> ${url} (${files.join(', ')})`)
}
